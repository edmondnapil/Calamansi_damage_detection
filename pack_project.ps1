# Creates a zip of this project for copying to another computer.
#
# Included: source code, dataset, trained models, reports.
# Left out (re-created by setup.ps1 or not needed to run the app):
#   backend\.venv, frontend\node_modules, frontend\dist, backend\ood_data (1.6 GB,
#   only needed to retrain the leaf check), backend\data, caches.
# backend\.env (Supabase secret key) is left out on purpose. Copy it separately
# by USB; never upload it or send it in a chat.
#
# Usage (PowerShell, in the project folder):
#   powershell -ExecutionPolicy Bypass -File .\pack_project.ps1
#   powershell -ExecutionPolicy Bypass -File .\pack_project.ps1 -Destination D:\

param([string]$Destination = [Environment]::GetFolderPath("Desktop"))

$ErrorActionPreference = "Stop"
$root = $PSScriptRoot
$zipPath = Join-Path $Destination "Calamansi-Leaf-Detection.zip"

$excludeDirs = @(
    "backend\.venv", "backend\ood_data", "backend\data", "frontend\node_modules",
    "frontend\dist", ".git", ".pytest_cache"
)
$excludeFiles = @("backend\.env", "frontend\.env", "backend\outputs\gate_embeddings_cache.npz",
                  "frontend\tsconfig.tsbuildinfo")

function Test-Excluded([string]$rel) {
    foreach ($d in $excludeDirs) { if ($rel -eq $d -or $rel.StartsWith("$d\")) { return $true } }
    if ($excludeFiles -contains $rel) { return $true }
    if ($rel -like "backend\outputs\gate_embeddings_cache*") { return $true }  # regenerated by train_gate.py
    if ($rel -match '(^|\\)__pycache__(\\|$)' -or $rel.EndsWith(".pyc")) { return $true }
    return $false
}

Write-Host "Collecting files..."
$files = Get-ChildItem -Path $root -Recurse -File -Force | Where-Object {
    -not (Test-Excluded $_.FullName.Substring($root.Length + 1))
}

if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [System.IO.Compression.ZipFile]::Open($zipPath, "Create")
try {
    $top = "Calamansi-Leaf-Detection"
    foreach ($f in $files) {
        $rel = $f.FullName.Substring($root.Length + 1)
        [void][System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile(
            $zip, $f.FullName, "$top/" + $rel.Replace("\", "/"), "Optimal")
    }
} finally {
    $zip.Dispose()
}

$sizeMb = [math]::Round((Get-Item $zipPath).Length / 1MB, 1)
Write-Host ""
Write-Host "Created $zipPath ($($files.Count) files, $sizeMb MB)" -ForegroundColor Green
if (Test-Path (Join-Path $root "backend\.env")) {
    Write-Host "NOT included: backend\.env (Supabase key). Copy it separately to" -ForegroundColor Yellow
    Write-Host "  Calamansi-Leaf-Detection\backend\.env on the other computer (USB only)." -ForegroundColor Yellow
}
Write-Host "On the other computer: extract the zip to a short path such as C:\ (giving C:\Calamansi-Leaf-Detection),"
Write-Host "then double-click setup.bat."
